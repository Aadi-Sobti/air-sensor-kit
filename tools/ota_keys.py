#!/usr/bin/env python3
"""Create the OTA signing key (OTA = updating sensors over WiFi) and build its public half into the firmware.

  python3 tools/ota_keys.py dev       # dev key: secrets/ota-dev-private.pem + firmware/src/dev/ota_key_dev.cpp
  python3 tools/ota_keys.py release   # FOUNDER ONLY (M11): the production key for every sensor in the field

The private key never leaves secrets/ (gitignored) and is never printed. Sensors only accept updates signed with
the private key whose public half is built into their firmware, so:
  * losing the RELEASE private key = no more updates for the whole fleet (back it up offline, twice);
  * leaking it = anyone could push firmware to every sensor.
Uses the system `openssl` (RSA-2048; the ESP8266 core's signature check supports RSA, see tools/ota_publish.py).
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SECRETS = ROOT / "secrets"

TARGETS = {
    "dev": dict(private=SECRETS / "ota-dev-private.pem", public=ROOT / "firmware/keys/ota_dev_public.pem",
                cpp=ROOT / "firmware/src/dev/ota_key_dev.cpp", fn="otaDevPublicKeyPem",
                note="Dev builds only (src/dev/ is excluded from release builds)."),
    "release": dict(private=SECRETS / "ota-release-private.pem", public=ROOT / "firmware/keys/ota_release_public.pem",
                    cpp=ROOT / "firmware/src/ota_key_release.cpp", fn="otaReleasePublicKeyPem",
                    note="PRODUCTION key: every release build trusts it."),
}


def public_pem(private: Path) -> str:
    return subprocess.run(["openssl", "rsa", "-in", str(private), "-pubout"], check=True, capture_output=True,
                          text=True).stdout


def cpp_source(fn: str, pem: str, note: str) -> str:
    lines = "\n".join(f'    "{line}\\n"' for line in pem.strip().splitlines())
    return (f"// Generated by tools/ota_keys.py. {note}\n// Public key only: safe to commit. The private half is in "
            f"secrets/ (never committed).\n#include <pgmspace.h>\n\nstatic const char kPem[] PROGMEM =\n{lines};\n\n"
            f"const char* {fn}() {{ return kPem; }}\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("which", choices=sorted(TARGETS))
    ap.add_argument("--yes-i-am-the-founder", action="store_true", help="required for 'release'")
    args = ap.parse_args(argv)
    t = TARGETS[args.which]
    if args.which == "release" and not args.yes_i_am_the_founder:
        print("The production key is created by the founder only (it must be backed up offline). "
              "Re-run with --yes-i-am-the-founder.")
        return 2
    SECRETS.mkdir(exist_ok=True)
    priv: Path = t["private"]
    if priv.exists():
        print(f"Keeping the existing private key {priv.relative_to(ROOT)} (delete it yourself to start over).")
    else:
        old = os.umask(0o077)
        try:
            subprocess.run(["openssl", "genrsa", "-out", str(priv), "2048"], check=True, capture_output=True)
        finally:
            os.umask(old)
        priv.chmod(0o600)
        print(f"Created {priv.relative_to(ROOT)} (private; never commit or share it).")
    pem = public_pem(priv)
    t["public"].parent.mkdir(parents=True, exist_ok=True)
    t["public"].write_text(pem)
    t["cpp"].write_text(cpp_source(t["fn"], pem, t["note"]))
    print(f"Wrote {t['public'].relative_to(ROOT)} and {t['cpp'].relative_to(ROOT)}.")
    if args.which == "release":
        print("NOW: copy the private key to two offline places (e.g. two USB sticks in different homes).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
